const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const sourceFiles = ["index.html", "styles.css", "js/core.js", "js/audio.js", "js/render.js", "js/main.js"];
const weights = [400, 500, 600];
const chunkSize = 40;
const outDir = path.join(root, "assets", "fonts");

async function fetchCss(chunk, weight) {
  const text = encodeURIComponent(chunk.join(""));
  const url = `https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@${weight}&display=swap&text=${text}`;
  const response = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0" } });
  if (!response.ok) throw new Error(`Font CSS request failed: ${response.status}`);
  return response.text();
}

async function downloadFont(fontUrl, filename) {
  const response = await fetch(fontUrl, { headers: { "User-Agent": "Mozilla/5.0" } });
  if (!response.ok) throw new Error(`Font download failed: ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  fs.writeFileSync(path.join(outDir, filename), bytes);
  return bytes.length;
}

async function main() {
  fs.mkdirSync(outDir, { recursive: true });
  const source = sourceFiles.map((file) => fs.readFileSync(path.join(root, file), "utf8")).join("");
  const characters = [...new Set([...source].filter((character) => /[^\x00-\x7f]/.test(character)))].sort();
  const chunks = [];
  for (let index = 0; index < characters.length; index += chunkSize) {
    chunks.push(characters.slice(index, index + chunkSize));
  }

  const rules = [];
  let totalBytes = 0;
  for (let chunkIndex = 0; chunkIndex < chunks.length; chunkIndex += 1) {
    const chunk = chunks[chunkIndex];
    const unicodeRange = chunk.map((character) => `U+${character.codePointAt(0).toString(16).toUpperCase()}`).join(", ");
    for (const weight of weights) {
      const css = await fetchCss(chunk, weight);
      const match = css.match(/url\((https:[^)]+)\)/);
      if (!match) throw new Error(`Could not find font URL in CSS for chunk ${chunkIndex + 1}`);
      const filename = `boat-sc-${String(chunkIndex + 1).padStart(2, "0")}-${weight}.ttf`;
      totalBytes += await downloadFont(match[1], filename);
      rules.push(`@font-face {
  font-family: "Boat Sans SC";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  unicode-range: ${unicodeRange};
  src: url("./${filename}") format("truetype");
}`);
    }
  }
  fs.writeFileSync(
    path.join(outDir, "fonts.css"),
    `/* Generated by scripts/build-fonts.cjs. Noto Sans SC is licensed under OFL 1.1. */\n${rules.join("\n\n")}\n`
  );
  console.log(`Generated ${chunks.length} chunks, ${chunks.length * weights.length} font files, ${Math.round(totalBytes / 1024)} KiB.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
